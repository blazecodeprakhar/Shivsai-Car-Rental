const validatedFleet = carConfigs.map((c) => {
  const dir = path.join(assetsDir, c.folder)
  if (!fs.existsSync(dir)) {
    throw new Error(`Directory not found: ${dir}`)
  }
  const images = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.png') || f.endsWith('.jpg'))
    .map((f) => `/cars_assets/${c.folder}/${f}`)

  return {
    ...c,
    image: images[0],
    images,
    imageCount: images.length,
    terms: {
      kmLimit: c.kmLimit,
      extraKm: c.extraKm,
      extraHr: '₹150 / hr after 24 hrs',
      deposit: "Customer's 2-wheeler OR ₹10,000 security deposit",
      documents: 'Original Aadhaar Card, PAN Card & Driving Licence',
      fuel: 'Maintain initial level (Extra fuel non-refundable)',
    },
  }
})

console.log('Total verified cars:', validatedFleet.length)
validatedFleet.forEach((c) => {
  console.log(`- ${c.name} (${c.category}): ${c.priceDisplay} [${c.imageCount} images] -> ${c.image}`)
})

fs.writeFileSync(
  path.join(root, 'scripts', 'generated_fleet.json'),
  JSON.stringify(validatedFleet, null, 2)
)
